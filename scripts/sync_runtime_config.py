def load_config() -> dict:
    return json.loads(CONFIG_PATH.read_text(encoding="utf-8"))


def write_text_if_changed(path: Path, content: str) -> bool:
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        if existing == content:
            return False
        if path.suffix.lower() == ".json":
            try:
                if json.loads(existing) == json.loads(content):
                    return False
            except json.JSONDecodeError:
                pass
    path.write_text(content, encoding="utf-8")
    return True


def write_browser_sniffer_config(config: dict) -> None:
    web = config["web"]
    sniffer = config["browser_sniffer"]
    api_base_url = f"{web['scheme']}://{web['host']}:{web['port']}"
    content = (
        "// Generated by scripts/sync_runtime_config.py from config/video_orchestrator.json.\n"
        "// Do not edit port or endpoint values by hand.\n"
        "export const ORCHESTRATOR_CONFIG = "
        + json.dumps(
            {
                "apiBaseUrl": api_base_url,
                "planPath": sniffer["plan_path"],
                "outputDir": sniffer["output_dir"],
            },
            ensure_ascii=False,
            indent=2,
        )
        + ";\n\n"
        "export function snifferPlanEndpoint() {\n"
        "  return `${ORCHESTRATOR_CONFIG.apiBaseUrl}${ORCHESTRATOR_CONFIG.planPath}`;\n"
        "}\n\n"
        "export function snifferManifestProbeEndpoint(captureId) {\n"
        "  return `${ORCHESTRATOR_CONFIG.apiBaseUrl}/sniffed-media/${encodeURIComponent(captureId)}/manifest-probe`;\n"
        "}\n"
    )
    write_text_if_changed(BROWSER_SNIFFER_DIR / "orchestrator-config.js", content)

def write_browser_sniffer_supported_media() -> None:
    content = (
        "// Generated by scripts/sync_runtime_config.py from runtime/media_protocols.py.\n"
        "// Do not edit protocol entries by hand.\n\n"
        "const SUPPORTED_MEDIA = "
        + json.dumps(browser_protocols(), ensure_ascii=False, indent=2)
        + ";\n\nexport default SUPPORTED_MEDIA;\n"
    )
    write_text_if_changed(BROWSER_SNIFFER_DIR / "supported.js", content)

def write_browser_manifest() -> None:
    manifest = {
        "manifest_version": 3,
        "name": "Video Orchestrator Sniffer",
        "version": "0.1.0",
        "description": "Detect audio/video media and HLS/DASH manifests, then submit planning requests to a local video-download-orchestrator API.",
        "permissions": ["webRequest", "tabs", "storage"],
        "host_permissions": ["http://*/*", "https://*/*", "http://127.0.0.1:*/*"],
        "action": {
            "default_popup": "popup.html",
            "default_title": "Video Orchestrator",
        },
        "background": {
            "service_worker": "background.js",
            "type": "module",
        },
    }
    write_text_if_changed(
        BROWSER_SNIFFER_DIR / "manifest.json",
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
    )


